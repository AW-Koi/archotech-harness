namespace DevHarness.Cli;

/// <summary>Writes .rwh-editor.csx, which gives an editor the script's references and default usings.</summary>
/// <remarks>A script opts in with #load ".rwh-editor.csx"; rwh run regenerates the file next to the script.</remarks>
public static class EditorSupport
{
    public const string FileName = ".rwh-editor.csx";

    private static readonly string[] FrameworkPrefixes = ["System.", "Microsoft.", "mscorlib", "netstandard", "WindowsBase"];

    public static void Write(string path, IEnumerable<string> managedReferences, IEnumerable<string> usings)
    {
        var lines = new List<string> { "// Generated by rwh for editor IntelliSense. rwh run rewrites it; do not edit." };
        lines.AddRange(managedReferences
            .Where(r => !FrameworkPrefixes.Any(p => Path.GetFileName(r).StartsWith(p, StringComparison.OrdinalIgnoreCase)))
            .Select(r => $"#r \"{r}\""));
        lines.AddRange(usings.Select(u => $"using {u};"));
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllLines(path, lines);
    }
}
